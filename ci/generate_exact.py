#!/usr/bin/env python3
"""Generate Lean statements of exact averages t_{n,m}(G) from data/fixed_n.csv.

The CSV is a copy of gradient-key-impl/data/small/fixed_n.csv (excess X = t - C(m)).
The values are proof targets only: Lean checks every generated theorem.

Writes
  Section3/ExactAnalytic.lean  -- C(m) for 2 <= m <= 64 and every pair n <= 6 covered by
                                  Propositions 3.3 (m <= 3), 3.5 and 3.6;
  Section3/Table2Small.lean    -- Table 2 rows n = 1, 2, 3 (all pairs of these rows are analytic).
"""
import csv
from fractions import Fraction
from math import comb, factorial
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def cost(m):
    l = m.bit_length() - 1
    return Fraction(l + 2) - Fraction(2 ** (l + 1), m)


def rat(x):
    return f"({x.numerator} : ℝ) / {x.denominator}"


def route(n, m):
    if m <= 3:
        return "small"
    if 2 ** n <= m + n:
        return "dense"
    if n >= 3 and m + n + 1 == 2 ** n:
        return "near_one"
    if n >= 4 and m + n + 2 == 2 ** n:
        return "near_two"
    return "path"


def read_rows():
    rows = {}
    with (ROOT / "data/fixed_n.csv").open(newline="") as f:
        for r in csv.DictReader(f):
            n, m = int(r["n"]), int(r["m"])
            rows[n, m] = Fraction(int(r["excess_numerator"]), int(r["excess_denominator"]))
    assert set(rows) == {(n, m) for n in range(1, 7) for m in range(2, 2 ** n + 1)}
    for (n, m), x in rows.items():
        scaled = (cost(m) + x) * Fraction(factorial(2 ** n), factorial(2 ** n - m))
        assert scaled.denominator == 1, (n, m)
        method = route(n, m)
        if method in ("small", "dense"):
            assert x == 0, (n, m)
        if method == "near_one":
            assert x == Fraction(2 ** n, m * comb(2 ** n, n + 1)), (n, m)
        if method == "near_two":
            assert x == Fraction(2 ** (n - 2) * (3 ** n - 2 * n - 1), m * comb(2 ** n, n + 2)), (n, m)
    return rows


HEADER = ["noncomputable section", "", "namespace GradientKey.Concrete", ""]


def exact_analytic(rows):
    out = ["import Examples", "",
           "/-!", "# Exact averages from Propositions 3.3, 3.5 and 3.6",
           "",
           "`C(m)` for `2 ≤ m ≤ 64`, and `t_{n,m}(G)` for every pair `n ≤ 6`, `2 ≤ m ≤ 2^n` with",
           "`m ≤ 3` (excess `0`), `2^n ≤ m + n` (Proposition 3.5) or `m + n + 1 = 2^n`, `m + n + 2 = 2^n`",
           "(Proposition 3.6). Generated by `ci/generate_exact.py` from `data/fixed_n.csv`.",
           "-/", ""] + HEADER
    out += ["/-- `C(m) = k + 2 - 2^{k+1}/m` for `2^k ≤ m < 2^{k+1}`. -/",
            "theorem completeCost_of_log {m : ℕ} (k : ℕ) (h1 : 2 ^ k ≤ m) (h2 : m < 2 ^ (k + 1)) :",
            "    completeCost m = (k : ℝ) + 2 - 2 ^ (k + 1) / (m : ℝ) := by",
            "  rw [completeCost, Nat.log_eq_of_pow_le_of_lt_pow h1 h2]", ""]
    for m in range(2, 65):
        k = m.bit_length() - 1
        out += [f"theorem completeCost_val_{m} : completeCost {m} = {rat(cost(m))} := by",
                f"  rw [completeCost_of_log {k} (by norm_num) (by norm_num)]",
                "  all_goals norm_num", ""]
    count = 0
    for (n, m) in sorted(rows):
        method = route(n, m)
        if method == "path":
            continue
        count += 1
        t = cost(m) + rows[n, m]
        doc = {"small": "Proposition 3.3, `m ≤ 3`", "dense": "Proposition 3.5",
               "near_one": "Proposition 3.6, first formula",
               "near_two": "Proposition 3.6, second formula"}[method]
        out += [f"/-- `t_{{{n},{m}}}(G) = {t}` ({doc}). -/",
                f"theorem exact_n{n}_m{m} : tG {n} {m} (by norm_num) = {rat(t)} := by"]
        if method == "small":
            out += [f"  have h := excess_small (n := {n}) (m := {m}) (by norm_num) (by norm_num) "
                    "(by norm_num) (by norm_num)",
                    f"  rw [completeCost_val_{m}] at h",
                    "  linarith"]
        elif method == "dense":
            out += [f"  rw [prop_dense (n := {n}) (m := {m}) (by norm_num) (by norm_num) (by norm_num) "
                    f"(by norm_num), completeCost_val_{m}]",
                    "  all_goals norm_num"]
        else:
            d = 1 if method == "near_one" else 2
            decl = "prop_near_dense_one" if d == 1 else "prop_near_dense_two"
            out += [f"  have hch : (2 ^ {n}).choose ({n} + {d}) = {comb(2 ** n, n + d)} := by",
                    "    rw [Nat.choose_eq_descFactorial_div_factorial]",
                    "    rfl",
                    f"  have h := {decl} (n := {n}) (m := {m}) (by norm_num) (by norm_num)",
                    f"  rw [completeCost_val_{m}, hch] at h",
                    "  norm_num at h",
                    "  linarith"]
        out.append("")
    out += ["end GradientKey.Concrete"]
    (ROOT / "Section3/ExactAnalytic.lean").write_text("\n".join(out) + "\n")
    return count


def table2(rows, ns, name, imports):
    out = [f"import {x}" for x in imports] + ["",
           "/-!", f"# Table 2, rows `n = {', '.join(map(str, ns))}`", "",
           "The largest excess `t_{n,m}(G) - C(m)` over `2 ≤ m ≤ 2^n`, the `m` where it is attained,",
           "and, for `n ≥ 3`, that this `m` is unique. Generated by `ci/generate_exact.py`.",
           "-/", ""] + HEADER
    for n in ns:
        es = {m: rows[n, m] for m in range(2, 2 ** n + 1)}
        best = max(es.values())
        arg = [m for m in es if es[m] == best]
        assert n < 3 or arg == [2 ** (n - 1)]
        out += [f"/-- Table 2, `n = {n}`: `t_{{{n},m}}(G) - C(m) ≤ {best}` for `2 ≤ m ≤ 2^{n}`. -/",
                f"theorem table2_n{n}_bound (m : ℕ) (hm : 2 ≤ m) (hs : m ≤ 2 ^ {n}) :",
                f"    tG {n} m (by norm_num) - completeCost m ≤ {rat(best)} := by",
                "  norm_num at hs", "  interval_cases m"]
        for m in es:
            out += [f"  · rw [exact_n{n}_m{m}, completeCost_val_{m}]", "    all_goals norm_num"]
        out += ["", f"/-- Table 2, `n = {n}`: the maximum `{best}` is attained at `m = {arg[0]}`. -/",
                f"theorem table2_n{n}_attained :",
                f"    tG {n} {arg[0]} (by norm_num) - completeCost {arg[0]} = {rat(best)} := by",
                f"  rw [exact_n{n}_m{arg[0]}, completeCost_val_{arg[0]}]", "  all_goals norm_num", ""]
        if n >= 3:
            out += [f"/-- Table 2, `n = {n}`: `m = {arg[0]}` is the only `m` attaining the maximum. -/",
                    f"theorem table2_n{n}_unique (m : ℕ) (hm : 2 ≤ m) (hs : m ≤ 2 ^ {n})",
                    f"    (h : tG {n} m (by norm_num) - completeCost m = {rat(best)}) : m = {arg[0]} := by",
                    "  norm_num at hs", "  interval_cases m"]
            for m in es:
                if m == arg[0]:
                    out += ["  · rfl"]
                else:
                    out += [f"  · rw [exact_n{n}_m{m}, completeCost_val_{m}] at h", "    all_goals norm_num at h"]
            out.append("")
    out += ["end GradientKey.Concrete"]
    (ROOT / f"Section3/{name}.lean").write_text("\n".join(out) + "\n")


def main():
    rows = read_rows()
    count = exact_analytic(rows)
    table2(rows, [1, 2, 3], "Table2Small", ["ExactAnalytic"])
    print(f"ExactAnalytic: {count} pairs; Table2Small: rows 1-3")


if __name__ == "__main__":
    main()
